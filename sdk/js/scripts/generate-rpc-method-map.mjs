import { parseRegistry } from "./rpc-registry.mjs";
import { readFileSync } from "node:fs";
import { mkdir, writeFile } from "node:fs/promises";

const rpcProtoURL = new URL(
  "../../../api/proto/rpc/rpc.proto",
  import.meta.url,
);
const outputURL = new URL(
  "../gizclaw/generated/rpc/method-map.ts",
  import.meta.url,
);

const methods = parseRegistry(
  readFileSync(rpcProtoURL, "utf8"),
  "RPC_METHOD",
  "rpc_method",
);
const tools = parseRegistry(
  readFileSync(
    new URL("../../../api/proto/rpc/payload/tool.proto", import.meta.url),
    "utf8",
  ),
  "CLIENT_TOOL",
  "client_tool",
);

if (!Array.isArray(methods) || methods.length === 0) {
  throw new Error(
    "api/proto/rpc/rpc.proto must define RpcMethod entries before generating RPC TypeScript.",
  );
}

for (const item of methods) {
  if (
    typeof item.method !== "string" ||
    typeof item.request !== "string" ||
    typeof item.response !== "string" ||
    !Number.isSafeInteger(item.id)
  ) {
    throw new Error("invalid RpcMethod entry");
  }
}

const payloadTypes = Array.from(
  new Set(
    [...methods, ...tools].flatMap((item) => [item.request, item.response]),
  ),
).sort();
const imports = `import type { ${payloadTypes.join(", ")} } from "./payload-codec.ts";\n\n`;
const entries = methods
  .map(
    (item) =>
      `${deprecationComment(item)}  ${JSON.stringify(item.method)}: {\n    request: ${item.request};\n    response: ${item.response};\n  };`,
  )
  .join("\n");
const constants = methods
  .map(
    (item) =>
      `${deprecationComment(item)}  ${JSON.stringify(item.method)}: ${JSON.stringify(item.method)},`,
  )
  .join("\n");
const ids = methods
  .map(
    (item) =>
      `${deprecationComment(item)}  ${JSON.stringify(item.method)}: ${item.id},`,
  )
  .join("\n");

const text = `/* eslint-disable */\n// This file is generated by sdk/js/scripts/generate-rpc-method-map.mjs.\n// Do not edit by hand.\n\n${imports}export type RPCMethodMap = {\n${entries}\n};\n\nexport type RPCMethodName = keyof RPCMethodMap;\n\nexport const RPC_METHODS = {\n${constants}\n} as const satisfies Record<RPCMethodName, RPCMethodName>;\n\nexport const RPC_METHOD_IDS = {\n${ids}\n} as const satisfies Record<RPCMethodName, number>;\n`;

const toolText = `\nexport type ClientToolMap = {\n${tools.map((item) => `${item.id}: { request: ${item.request}; response: ${item.response}; };`).join("\n")}\n};\nexport type ClientToolID = keyof ClientToolMap;\nexport const CLIENT_TOOL_IDS = ${JSON.stringify(Object.fromEntries(tools.map((item) => [item.method, item.id])), null, 2)} as const;\nexport const CLIENT_TOOL_NAMES: Record<number, string> = ${JSON.stringify(Object.fromEntries(tools.map((item) => [item.id, item.method])), null, 2)};\n`;
await mkdir(new URL(".", outputURL), { recursive: true });
await writeFile(outputURL, text + toolText);

function deprecationComment(item) {
  return item.deprecation == null
    ? ""
    : `  /** @deprecated ${item.deprecation} */\n`;
}
