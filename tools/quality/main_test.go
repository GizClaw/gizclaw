func TestDiagnosticRepositoryPath(t *testing.T) {
	root := t.TempDir()
	tracked := map[string]bool{
		"examples/nested/pkg/file.go": true,
		"pkg/root.go":                 true,
	}
	tests := []struct {
		name     string
		module   string
		path     string
		want     string
		external bool
	}{
		{name: "module relative", module: "examples/nested", path: "pkg/file.go", want: "examples/nested/pkg/file.go"},
		{name: "root relative", module: "examples/nested", path: "pkg/root.go", want: "pkg/root.go"},
		{name: "absolute", module: "examples/nested", path: filepath.Join(root, "pkg/root.go"), want: "pkg/root.go"},
		{name: "slash normalized", module: "examples/nested", path: "pkg/../pkg/file.go", want: "examples/nested/pkg/file.go"},
		{name: "inside unknown", module: "examples/nested", path: "unknown.go", want: "examples/nested/unknown.go"},
		{name: "outside", module: ".", path: "../outside.go", external: true},
		{name: "prefix confusion", module: ".", path: "../repository-other/file.go", external: true},
	}
	for _, test := range tests {
		t.Run(test.name, func(t *testing.T) {
			got, external := diagnosticRepositoryPath(root, test.module, test.path, tracked)
			if got != test.want || external != test.external {
				t.Fatalf("diagnosticRepositoryPath() = %q, %t, want %q, %t", got, external, test.want, test.external)
			}
		})
	}
}

func TestModernizeDiagnosticsFromOutput(t *testing.T) {
	root := t.TempDir()
	writeTestFile(t, root, "handwritten.go", "package handwritten\n")
	writeTestFile(t, root, "generated.go", "// Code generated by test. DO NOT EDIT.\npackage generated\n")
	writeTestFile(t, root, "third_party/source.go", "package thirdparty\n")
	writeTestFile(t, root, "guides/node_modules/dependency.go", "package dependency\n")
	tracked := map[string]bool{
		"generated.go":          true,
		"handwritten.go":        true,
		"third_party/source.go": true,
	}
	output := strings.Join([]string{
		"handwritten.go:1:1: handwritten diagnostic",
		"generated.go:1:1: generated diagnostic",
		"third_party/source.go:1:1: third-party diagnostic",
		"guides/node_modules/dependency.go:1:1: excluded dependency diagnostic",
		"../external.go:1:1: external diagnostic",
		"package loading failed",
		"",
	}, "\n")
	handwritten, exemptible, failed := modernizeDiagnosticsFromOutput(root, ".", []byte(output), tracked)
	if !slices.Equal(handwritten, []string{"handwritten.go:1:1: handwritten diagnostic"}) {
		t.Fatalf("handwritten = %q", handwritten)
	}
	wantExemptible := []string{
		"generated.go:1:1: generated diagnostic",
		"third_party/source.go:1:1: third-party diagnostic",
	}
	if !slices.Equal(exemptible, wantExemptible) {
		t.Fatalf("exemptible = %q, want %q", exemptible, wantExemptible)
	}
	if !failed {
		t.Fatal("non-diagnostic tool output was not retained as a failure")
	}
}

func TestValidateModernizeExemptions(t *testing.T) {
	root := t.TempDir()
	writeTestFile(t, root, "generated.go", "// Code generated by test. DO NOT EDIT.\npackage generated\n")
	writeTestFile(t, root, "handwritten.go", "package handwritten\n")
	writeTestFile(t, root, "third_party/source.go", "package thirdparty\n")
	tracked := map[string]bool{
		"generated.go":          true,
		"handwritten.go":        true,
		"third_party/source.go": true,
	}
	valid := []byte("generated.go:1:1: generated diagnostic\nthird_party/source.go:1:1: third-party diagnostic\n")
	if err := validateModernizeExemptions(root, valid, tracked); err != nil {
		t.Fatalf("valid exemptions: %v", err)
	}

	tests := map[string][]byte{
		"handwritten":       []byte("handwritten.go:1:1: diagnostic\n"),
		"unknown":           []byte("unknown.go:1:1: diagnostic\n"),
		"absolute":          []byte(filepath.Join(root, "generated.go") + ":1:1: diagnostic\n"),
		"path only":         []byte("generated.go\n"),
		"wildcard":          []byte("generated/*.go:1:1: diagnostic\n"),
		"missing newline":   []byte("generated.go:1:1: diagnostic"),
		"duplicate":         []byte("generated.go:1:1: diagnostic\ngenerated.go:1:1: diagnostic\n"),
		"reverse sorted":    []byte("third_party/source.go:1:1: diagnostic\ngenerated.go:1:1: diagnostic\n"),
		"blank middle line": []byte("generated.go:1:1: diagnostic\n\nthird_party/source.go:1:1: diagnostic\n"),
	}
	for name, contents := range tests {
		t.Run(name, func(t *testing.T) {
			if err := validateModernizeExemptions(root, contents, tracked); err == nil {
				t.Fatal("invalid exemptions were accepted")
			}
		})
	}
}

func TestCheckModernizeExemptions(t *testing.T) {
	root := t.TempDir()
	writeTestFile(t, root, "generated.go", "// Code generated by test. DO NOT EDIT.\npackage generated\n")
	writeTestFile(t, root, "tools/quality/modernize.exemptions", "stale\n")
	tracked := map[string]bool{"generated.go": true}
	diagnostics := []string{"generated.go:1:1: generated diagnostic"}

	if err := checkModernizeExemptions(root, "tools/quality/modernize.exemptions", diagnostics, true, tracked); err != nil {
		t.Fatalf("write exemptions: %v", err)
	}
	want := "generated.go:1:1: generated diagnostic\n"
	got, err := os.ReadFile(filepath.Join(root, "tools/quality/modernize.exemptions"))
	if err != nil {
		t.Fatal(err)
	}
	if string(got) != want {
		t.Fatalf("written exemptions = %q, want %q", got, want)
	}
	if matches, err := filepath.Glob(filepath.Join(root, "tools/quality/.modernize-exemptions-*")); err != nil || len(matches) != 0 {
		t.Fatalf("temporary exemptions remain: %q, %v", matches, err)
	}
	if err := checkModernizeExemptions(root, "tools/quality/modernize.exemptions", diagnostics, false, tracked); err != nil {
		t.Fatalf("compare exemptions: %v", err)
	}
	if err := checkModernizeExemptions(root, "tools/quality/modernize.exemptions", nil, false, tracked); err == nil {
		t.Fatal("stale exemption was accepted")
	}
	if err := checkModernizeExemptions(root, "tools/quality/modernize.exemptions", nil, true, tracked); err != nil {
		t.Fatalf("write empty exemptions: %v", err)
	}
	if err := checkModernizeExemptions(root, "tools/quality/modernize.exemptions", nil, false, tracked); err != nil {
		t.Fatalf("compare empty exemptions: %v", err)
	}
	empty, err := os.ReadFile(filepath.Join(root, "tools/quality/modernize.exemptions"))
	if err != nil {
		t.Fatal(err)
	}
	if len(empty) != 0 {
		t.Fatalf("empty exemptions = %q", empty)
	}
}

func TestRunModernizeDoesNotWriteOnFailure(t *testing.T) {
	tests := map[string]string{
		"handwritten diagnostic":                         "#!/bin/sh\nprintf '%s\\n' 'handwritten.go:1:1: diagnostic'\nexit 3\n",
		"analyzer failure with diagnostic-shaped output": "#!/bin/sh\nprintf '%s\\n' 'generated.go:1:1: diagnostic'\nexit 1\n",
		"tool failure":                                   "#!/bin/sh\nprintf '%s\\n' 'package loading failed'\nexit 1\n",
		"silent failure":                                 "#!/bin/sh\nexit 1\n",
	}
	for name, script := range tests {
		t.Run(name, func(t *testing.T) {
			root := newTestRepository(t)
			exemptions := "tools/quality/modernize.exemptions"
			writeTestFile(t, root, exemptions, "sentinel\n")
			writeTestFile(t, root, "handwritten.go", "package handwritten\n")
			writeTestFile(t, root, "generated.go", "// Code generated by test. DO NOT EDIT.\npackage generated\n")
			runGit(t, root, "add", "go.mod", "generated.go", "handwritten.go", exemptions)
			analyzer := filepath.Join(root, "fake-modernize")
			writeExecutable(t, analyzer, script)
			if err := runModernize(root, analyzer, exemptions, true); err == nil {
				t.Fatal("runModernize succeeded")
			}
			contents, err := os.ReadFile(filepath.Join(root, exemptions))
			if err != nil {
				t.Fatal(err)
			}
			if string(contents) != "sentinel\n" {
				t.Fatalf("exemptions changed to %q", contents)
			}
		})
	}
}

func TestRepositoryOwnedFileRejectsSymlinks(t *testing.T) {
	root := t.TempDir()
	writeTestFile(t, root, "tools/quality/modernize.exemptions", "")
	external := t.TempDir()
	if err := os.Symlink(external, filepath.Join(root, "linked-directory")); err != nil {
		t.Fatal(err)
	}
	if _, err := repositoryOwnedFile(root, "linked-directory/modernize.exemptions"); err == nil {
		t.Fatal("symlinked parent directory was accepted")
	}
	if err := os.Symlink(
		filepath.Join(root, "tools/quality/modernize.exemptions"),
		filepath.Join(root, "linked-exemptions"),
	); err != nil {
		t.Fatal(err)
	}
	if _, err := repositoryOwnedFile(root, "linked-exemptions"); err == nil {
		t.Fatal("symlinked exemption file was accepted")
	}
}

