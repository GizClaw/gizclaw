func TestClassifySource(t *testing.T) {
	root := t.TempDir()
	writeTestFile(t, root, "generated.go", "// Code generated by test. DO NOT EDIT.\npackage generated\n")
	writeTestFile(t, root, "generated_test.go", "package generated\n")
	writeTestFile(t, root, "generator/main.go", "package main\n\nconst output = `// Code generated by test. DO NOT EDIT.`\n")
	writeTestFile(t, root, "pkgs/gizclaw/api/apitypes/codegen.go", "package apitypes\n")
	writeTestFile(t, root, "sdk/c/gizclaw/generated/rpc.pb.c", "/* generated */\n")
	writeTestFile(t, root, "third_party/upstream/source.go", "package upstream\n")
	external := filepath.Join(t.TempDir(), "generated.go")
	if err := os.WriteFile(external, []byte("// Code generated by test. DO NOT EDIT.\npackage generated\n"), 0o600); err != nil {
		t.Fatal(err)
	}
	if err := os.Symlink(external, filepath.Join(root, "generated-link.go")); err != nil {
		t.Fatal(err)
	}

	type sourceTest struct {
		name       string
		file       string
		tracked    bool
		provenance sourceProvenance
	}
	tests := []sourceTest{
		{name: "standard generated preamble", file: "generated.go", tracked: true, provenance: provenanceGenerated},
		{name: "misleading filename", file: "generated_test.go", tracked: true, provenance: provenanceHandwritten},
		{name: "marker inside template", file: "generator/main.go", tracked: true, provenance: provenanceHandwritten},
		{name: "explicit generated file", file: "pkgs/gizclaw/api/apitypes/codegen.go", tracked: true, provenance: provenanceGenerated},
		{name: "explicit generated directory", file: "sdk/c/gizclaw/generated/rpc.pb.c", tracked: true, provenance: provenanceGenerated},
		{name: "explicit third party", file: "third_party/upstream/source.go", tracked: true, provenance: provenanceThirdParty},
		{name: "untracked generated marker", file: "generated.go", tracked: false, provenance: provenanceHandwritten},
		{name: "tracked symlink to generated source", file: "generated-link.go", tracked: true, provenance: provenanceHandwritten},
	}
	for _, directory := range generatedDirectories {
		file := directory + "classification-fixture.go"
		writeTestFile(t, root, file, "package generated\n")
		tests = append(tests, sourceTest{
			name:       "generated directory " + directory,
			file:       file,
			tracked:    true,
			provenance: provenanceGenerated,
		})
	}
	tests = append(tests,
		sourceTest{
			name:       "untracked explicit generated directory",
			file:       "guides/node_modules/classification-fixture.go",
			provenance: provenanceExcluded,
		},
		sourceTest{
			name:       "untracked explicit third-party directory",
			file:       "third_party/upstream/source.go",
			provenance: provenanceExcluded,
		},
	)
	for _, test := range tests {
		t.Run(test.name, func(t *testing.T) {
			if got := classifySource(root, test.file, test.tracked); got != test.provenance {
				t.Fatalf("classifySource(%q) = %d, want %d", test.file, got, test.provenance)
			}
		})
	}
}

